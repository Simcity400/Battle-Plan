#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn market_dedicated_calls_forward_the_native_target_once() {
        for (i, site) in SITES.iter().enumerate() {
            assert!(SITES[..i].iter().all(|other| other.rva != site.rva));
            if let Some(target) = site.call_target {
                assert_eq!(site.sentinel[0], 0xe8);
                let displacement = i32::from_le_bytes(site.sentinel[1..5].try_into().unwrap());
                assert_eq!(
                    (site.rva as i64 + 5 + i64::from(displacement)) as usize,
                    target
                );
            }
        }
    }
}
