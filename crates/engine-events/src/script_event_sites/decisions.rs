/// Adjacent selected CALLs authenticate only bytes before the next patch.
pub const fn call_sentinel_len(site: Site) -> usize {
    if site.rva == REACTIVATE_TARGETED_DAYS.rva {
        REACTIVATE_TARGETED_STATE.rva - site.rva
    } else if site.rva == REQUEST_TARGETED_TIMED.rva {
        REQUEST_TARGETED.rva - site.rva
    } else {
        site.sentinel.len()
    }
}
