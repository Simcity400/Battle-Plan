/// The generated TypeScript contract: shared types, then every product's
/// parameters and reply. One deterministic file, exported explicitly.
pub fn typescript_contract() -> String {
    use ts_rs::TS;
    let mut declarations = vec![
        ReplayMetadata::decl(),
        BranchMetadata::decl(),
        RecordingGap::decl(),
        CountryMetadata::decl(),
        Artwork::decl(),
        LandOwners::decl(),
        FocusEntry::decl(),
        FocusOrder::decl(),
        FocusSegment::decl(),
        FocusProgress::decl(),
        FocusHistory::decl(),
        ResearchCoverage::decl(),
        ResearchOutcome::decl(),
        ResearchEntry::decl(),
        ResearchSlotState::decl(),
        ResearchDetails::decl(),
        ResearchModifiers::decl(),
        ResearchModifier::decl(),
        ResearchModifierSource::decl(),
        ResearchBonus::decl(),
        ResearchSlotHistory::decl(),
        ResearchProgress::decl(),
        ResearchHistory::decl(),
        protocol::MapGraphics::decl(),
        protocol::CampaignMapSettings::decl(),
        map_settings::Reply::decl(),
        transport::SourceReply::decl(),
    ];
    for product in products::PRODUCTS {
        declarations.extend((product.types)());
    }
    // Products may share a type (CountryParams, LandOwners); declare each name once.
    let mut seen = std::collections::BTreeSet::new();
    declarations.retain(|declaration| {
        let name = declaration
            .strip_prefix("type ")
            .and_then(|rest| rest.split_whitespace().next())
            .unwrap_or_default()
            .to_owned();
        seen.insert(name)
    });
    let mut text =
        String::from("// Generated by cargo run -p dashboard --bin export-types. Do not edit.\n");
    for declaration in declarations {
        text.push_str("export ");
        text.push_str(
            &declaration
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n"),
        );
        text.push('\n');
    }
    text
}

