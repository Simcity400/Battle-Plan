import assert from 'node:assert/strict';
import test from 'node:test';
import { withNativePage } from '../../../../tools/native-page.ts';

test('followed values are painted without a render, rows render, off-screen widgets follow when shown, a new root element keeps the follow, a message lands without painting, and 500 entries or a 439-row table paint in one pass, one write a changed cell', async () => {
  await withNativePage('follow', '/ui/src/dashboard/follow/follow.dom.fixture.tsx', page => page.stage('follow', async () => {
    const act = <T,>(expression: string) => page.evaluate<T>(`window.followFixture.${expression}`);
    await act('mount()');
    const sent = await act<string[]>('sent()');
    assert.equal(sent.filter(line => line.startsWith('follow')).length, 2, `the widget off screen follows nothing: ${sent.join('; ')}`);
    await act('deliver(24, [100, 80], [[7, 40], [3, 20]])');
    const mounted = await act<Record<string, number>>('renders()');
    for (let hour = 48; hour <= 480; hour += 24) await act(`deliver(${hour}, [${hour}, ${hour + 1}], [[7, ${hour}], [3, ${hour / 2}]])`);
    assert.deepEqual(await act('renders()'), mounted, 'values moved twenty times and nothing rendered');
    assert.equal(await act('text("measure")'), '480 481');
    assert.equal(await act('text("army")'), '480 240');
    assert.equal(await act('bars()'), '100% 50%');
    await act('deliver(504, [1, 2], [[7, 10], [5, 30], [3, 20]])');
    const grown = await act<Record<string, number>>('renders()');
    assert.equal(grown.army, mounted.army! + 1, 'a row came: one render');
    assert.equal(grown.measure, mounted.measure);
    assert.equal(await act('text("army")'), '10 30 20', 'the new row painted once it was rendered');
    await act('scrollToFar()');
    const far = (await act<string[]>('sent()')).find(line => line.startsWith('follow') && line.includes('commandPower'));
    assert.ok(far, 'shown: followed');
    const farId = far.split(' ')[1];
    await act('deliver(528, [1, 2], [[7, 10], [5, 30], [3, 20]])');
    assert.equal(await act('text("far")'), '528', 'painted once its first answer came');
    await act('scrollToTop()');
    assert.ok((await act<string[]>('sent()')).includes(`unfollow ${farId}`), 'off screen again: unfollowed');
    const received = await act<{ moved: number[]; frames: number; paints: number }>('receive(200)');
    assert.deepEqual(new Set(received.moved), new Set([200]), 'each of 50 entries took each of 200 messages');
    assert.deepEqual([received.frames, received.paints], [0, 0], 'entries nobody paints ask no frame');
    type Rounds = { rounds: { received: number; frames: number; paints: number; written: number }[]; last: string };
    const many = await act<Rounds>('paintMany(30)');
    assert.equal(many.last, String(499 + 29));
    assert.equal(many.rounds.length, 30);
    for (const round of many.rounds) assert.deepEqual(round, { received: 0, frames: 1, paints: 500, written: 500 }, 'a message of 500 entries: painted in one pass, once an entry, one write a cell');
    const table = await act<Rounds>('paintTable(439, 30)');
    assert.equal(table.last.replace(/\D/g, ''), String(438 * 7 + 29), 'the last row painted the last message');
    for (const round of table.rounds) assert.deepEqual(round, { received: 0, frames: 1, paints: 1, written: 439 }, 'a 439-row message: one paint, one write a value cell, the names untouched');
    await act('scrollToTop()');
    await act('swap(false)');
    const swapped = await act<string[]>('sent()');
    assert.equal(swapped.filter(line => line.startsWith('follow ') && line.includes('stability')).length, 1, 'followed while loading');
    await act('swap(true)');
    await act('swap(false)');
    const churn = (await act<string[]>('sent()')).slice(swapped.length).filter(line => /^(un)?follow /.test(line));
    assert.deepEqual(churn, [], 'its loading element replaced by its content and back: the follow is kept, never let go and asked again');
    const beforeContents = (await act<string[]>('sent()')).length;
    await act('contents(false)');
    const contents = (await act<string[]>('sent()')).slice(beforeContents);
    assert.equal(contents.filter(line => line.startsWith('follow ') && line.includes('warSupport')).length, 1,
      `a root with no box of its own is followed while its child is on screen: ${contents.join('; ')}`);
    await act('contents(true)');
    assert.deepEqual((await act<string[]>('sent()')).slice(beforeContents + contents.length).filter(line => /^(un)?follow /.test(line)), [],
      'its child replaced: the follow is kept');
    const contentsId = contents.find(line => line.startsWith('follow ') && line.includes('warSupport'))!.split(' ')[1];
    await act('contents(null)');
    assert.ok((await act<string[]>('sent()')).includes(`unfollow ${contentsId}`), 'gone: unfollowed');
  }, 120_000));
});
