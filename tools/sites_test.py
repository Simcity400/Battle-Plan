import importlib.util
import io
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch


SPEC = importlib.util.spec_from_file_location("sites", Path(__file__).with_name("sites.py"))
sites = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(sites)

COMPACT = """pub const ALONE: Rva = Rva(0x10);
pub const JOIN: Entry = Entry { name: "Join", rva: Rva(0x20), callers: &[caller(Rva(0x21), "Ally")] };
pub const END: Entry = Entry { name: "End", rva: Rva(0x30) };
pub const SCOPES: &[(Rva, &str)] = &[(Rva(0x40), "Daily"), (Rva(0x41), "Weekly")];
fn locate() { let _ = [Rva(0x50), Rva(0x51)]; }
#[cfg(test)]
mod tests { const FIXTURE: Rva = Rva(0x60); }
"""

SPREAD = """// A site with no other occurrence.
pub const ALONE: Rva =
    Rva(0x10);



pub const JOIN: Entry = Entry {
    // The entry.
    name: "Join",
    rva: Rva(0x20),
    callers: &[
        caller(
            Rva(0x21),
            /* a caller */ "Ally",
        ),
    ],
};
/* blank lines and comments between neighbours */


pub const END: Entry = Entry {

    name: "End",

    rva: Rva(0x30),
};
pub const SCOPES: &[(Rva, &str)] = &[
    (Rva(0x40), "Daily"),
    // name: "Weekly"
    (Rva(0x41), "Weekly"),
];
fn locate() {
    let _ = [
        Rva(0x50),
        Rva(0x51),
    ];
}
#[cfg(test)]
#[allow(dead_code, reason = "fixture")]
mod tests {
    const FIXTURE: Rva = Rva(0x60);
}
"""

HEADER = "//! Generated by `python tools/sites.py generate` from the game %s, the reference build; do not edit.\n" % (
    sites.BUILDS[next(iter(sites.BUILDS))])


def labels(text):
    return {rva: label for rva, label, _, _ in sites.declarations(text)}


class Declarations(unittest.TestCase):
    def test_each_site_takes_its_own_declaration_label_whatever_the_spacing(self):
        expected = {0x10: "ALONE", 0x20: "Join", 0x21: "Join", 0x30: "End",
                    0x40: "Daily", 0x41: "Weekly", 0x50: "locate", 0x51: "locate"}
        self.assertEqual(labels(COMPACT), expected)
        self.assertEqual(labels(SPREAD), expected)

    def test_any_rva_spelling_is_a_key_and_test_only_items_are_not(self):
        source = """fn locate() {
    let point = Rva /* spaced */ (0x10);
    let status = "Ready";
    let wrapped = Rva
        (0x11,);
}
/* outer /* nested Rva(0x12) */ still comment Rva(0x13) */
pub const RAW: Site = Site { name: r#"Raw"#, rva: Rva(0x14) };
#[cfg(test)]
const ONLY: Rva = if true { Rva(0x20) } else { Rva(0x21) };
#[cfg(all(test, windows))]
pub mod gated { const GATED: Rva = Rva(0x22); }
#[cfg(not(test))]
const KEPT: Rva = Rva(0x23);
"""
        self.assertEqual(labels(source), {0x10: "locate", 0x11: "locate", 0x14: "RAW", 0x23: "KEPT"})

    def test_test_items_literals_and_neighbours_never_make_or_name_production_keys(self):
        source = r'''#[cfg(test)]
const fn fixture() -> Rva { Rva(0x30) }
const REAL: Rva = Rva(0x31);
#[test]
fn checks() { let _ = Rva(0x32); }
#[cfg(all(target_pointer_width = "64", any(test, windows)))]
const WINDOWS: Rva = Rva(0x33);
#[cfg(all(test, not(miri)))]
const TESTED: Rva = Rva(0x34);
const TEXT: &str = "continued \
    Rva(0x35)";
const RAW: &core::ffi::CStr = cr#"quoted " Rva(0x36)"#;
const SUFFIXED: Rva = Rva(0x37usize);
fn pick(tag: &str) -> [Rva; 2] { [Rva(0x38), if "Other" == tag { Rva(0x39) } else { Rva(0x3a) }] }
'''
        self.assertEqual(labels(source), {0x31: "REAL", 0x33: "WINDOWS", 0x37: "SUFFIXED",
                                          0x38: "pick", 0x39: "pick", 0x3a: "pick"})

    def test_test_fields_and_const_generics_stay_within_their_own_declaration(self):
        source = """struct State {
    #[cfg(test)]
    reads: usize,
    #[cfg(test)]
    writes: usize
}
const SITE: Rva = Rva(0x40);
fn combat<const N: usize>(rows: [u8; N]) -> Rva { Rva(0x41) }
"""
        self.assertEqual(labels(source), {0x40: "SITE", 0x41: "combat"})

    def test_test_only_blocks_and_macros_end_at_their_own_braces(self):
        source = """fn site() -> Rva {
    #[cfg(test)]
    if disabled() { return Rva(0x50); } else { return Rva(0x51); }
    #[cfg(test)]
    if let Source::Fixture { .. } = source() { return Rva(0x55); } else { return Rva(0x56); }
    Rva(0x52)
}
#[cfg(test)]
thread_local! { static SEEN: Rva = Rva(0x53); }
const AFTER: Rva = Rva(0x54);
"""
        self.assertEqual(labels(source), {0x52: "site", 0x54: "AFTER"})

    def test_a_test_only_match_arm_ends_after_its_body(self):
        source = """fn site(source: Source) -> Rva {
    match source {
        #[cfg(test)]
        Source::Fixture { .. } => Rva(0x60),
        #[cfg(test)]
        Source::Generic => Ok::<_, Error>(Rva(0x62)).unwrap(),
        Source::Game => Rva(0x61),
    }
}
"""
        self.assertEqual(labels(source), {0x61: "site"})

    def test_published_names_survive_reformatting_of_the_generated_locator(self):
        with tempfile.TemporaryDirectory() as root:
            output = Path(root, "generated.rs")
            output.write_text(HEADER + 'pub(crate) static KEYS: &[Key] = &[\n    Key {\n        rva: 0x20,\n        name: "sites::JoinWar",\n'
                              '        kind: Kind::Code(0),\n    },\n    Key { rva: 0x2_1, name: "sites::Caller", kind: Kind::Code(1) },\n];\n',
                              encoding="utf-8")
            with patch.object(sites, "OUTPUT", str(output)):
                self.assertEqual(sites.published_names(), {0x20: "sites::JoinWar", 0x21: "sites::Caller"})

    def test_names_published_for_an_earlier_reference_move_with_their_sites(self):
        with tempfile.TemporaryDirectory() as root:
            output = Path(root, "generated.rs")
            output.write_text("//! Generated by `python tools/sites.py generate` from the game 1.0, the reference build; do not edit.\n"
                              'pub(crate) static KEYS: &[Key] = &[\n'
                              '    Key { rva: 0x10, name: "sites::Append", kind: Kind::Code(0) },\n'
                              '    Key { rva: 0x20, name: "sites::Destroy", kind: Kind::Code(1) },\n'
                              '    Key { rva: 0x30, name: "sites::Lost", kind: Kind::Code(2) },\n];\n', encoding="utf-8")
            with patch.object(sites, "OUTPUT", str(output)), patch.object(sites, "BUILDS", {"new": "2.0", "old": "1.0"}):
                with patch.object(sites, "addresses", return_value={0x10: 0x20, 0x20: 0x28}), self.assertRaises(SystemExit):
                    sites.published_names()
                with patch.object(sites, "addresses", return_value={0x10: 0x20, 0x20: 0x28, 0x30: 0x38}):
                    self.assertEqual(sites.published_names(),
                                     {0x20: "sites::Append", 0x28: "sites::Destroy", 0x38: "sites::Lost"})

    def test_a_failed_publication_restores_the_outputs_already_replaced(self):
        with tempfile.TemporaryDirectory() as root:
            first, second = Path(root, "generated.rs"), Path(root, "spec.json")
            first.write_text("old locator", encoding="utf-8")
            second.write_text("old spec", encoding="utf-8")
            replace = os.replace

            def refuse_the_spec(source, destination):
                if Path(destination) == second:
                    raise PermissionError("spec.json is in use")
                replace(source, destination)

            with patch.object(sites.os, "replace", side_effect=refuse_the_spec), self.assertRaises(PermissionError):
                sites.replace_files([(str(first), "new locator"), (str(second), "new spec")])
            self.assertEqual((first.read_text(encoding="utf-8"), second.read_text(encoding="utf-8")),
                             ("old locator", "old spec"))
            self.assertEqual(sorted(p.name for p in Path(root).iterdir()), ["generated.rs", "spec.json"])

    def test_a_promoted_reference_compares_other_builds_through_its_relocation(self):
        with tempfile.TemporaryDirectory() as root:
            executable = Path(root, "game.exe")
            executable.write_bytes(b"build")
            spec = {"keys": [], "vtables": []}
            seen = {}
            recorded = {"new": {0x10: 0x20, 0x11: 0x21}, "other": {0x10: 0x30, 0x99: 0x40}}

            def report(image, spec, expected, checked):
                seen[image] = expected
                return {}, [], set()

            builds = {"new": "3.0", "old": "2.0", "other": "1.0"}
            images = {build: build + " image" for build in builds}
            with (patch.object(sites, "BUILDS", builds), patch.object(sites, "report", side_effect=report),
                  patch.object(sites, "addresses", side_effect=lambda build: recorded.get(build, {})),
                  patch.object(sites, "source_keys", return_value={}), patch.object(sites, "exe", return_value=str(executable)),
                  patch.object(sites, "layout_checked", return_value=set()), patch.object(sites, "EXPECTED_WITHHELD", {}),
                  patch("sys.stdout", io.StringIO())):
                sites.verify(spec, images, "new", written=False, promoted_from="old")
                self.assertEqual(seen, {"new image": None, "old image": {0x20: 0x10, 0x21: 0x11}, "other image": {0x20: 0x30}})
                sites.verify(spec, images, "new", written=False)
                self.assertEqual(seen, {"new image": None, "old image": {}, "other image": recorded["other"]})

    def test_a_missing_or_truncated_generated_locator_is_refused_rather_than_renaming_sites(self):
        with tempfile.TemporaryDirectory() as root:
            for output in (Path(root, "missing.rs"), Path(root, "empty.rs")):
                if output.name == "empty.rs":
                    output.write_text("", encoding="utf-8")
                with patch.object(sites, "OUTPUT", str(output)), self.assertRaises(SystemExit):
                    sites.published_names()

    def test_published_names_win_and_new_keys_take_their_labels(self):
        with tempfile.TemporaryDirectory() as root:
            source = Path(root, "crates", "engine-x", "src", "sites.rs")
            source.parent.mkdir(parents=True)
            source.write_text(SPREAD, encoding="utf-8")
            output = Path(root, "generated.rs")
            output.write_text(HEADER + 'pub(crate) static KEYS: &[Key] = &[\n'
                              '    Key { rva: 0x20, name: "sites::JoinWar", kind: Kind::Code(0) },\n];\n', encoding="utf-8")
            with patch.object(sites, "ROOT", root), patch.object(sites, "OUTPUT", str(output)):
                keys = sites.source_keys()
        self.assertEqual({rva: name for rva, (name, _, _) in keys.items()}, {
            0x10: "sites::ALONE", 0x20: "sites::JoinWar", 0x21: "sites::Join", 0x30: "sites::End",
            0x40: "sites::Daily", 0x41: "sites::Weekly", 0x50: "sites::locate", 0x51: "sites::locate",
        })
        self.assertEqual(keys[0x21][1:], ("crates/engine-x/src/sites.rs", 13))


