"""Give every package selection's test build the workspace's features (Python 3.11+).

Cargo resolves features per command. `cargo test -p A` enables only what A's dependency
graph and A's own dev-dependencies request; `cargo test --workspace` enables what every
member requests. A crate resolved with other features is another build: it and every crate
above it compile from scratch once more for each selection that resolves it differently.

The check resolves `cargo tree` with test targets for the workspace and for each member, and
reports every crate a member's test build resolves with fewer features than the workspace's
test build, or builds only for build scripts and proc-macros where the workspace's test build
also builds it for the target with the same features (see `differences`). `--fix` makes them equal with generated dev-dependencies, which no non-test build
reads, so `cargo build` and checks without `--all-targets` keep their own features:

- each member's `[target.'cfg(all())'.dev-dependencies]` table names the workspace crates and
  the narrow third-party crates its tests build, with the workspace test build's features;
- `crates/test-unify` depends, with those features, on the third-party crates most test
  builds contain and on every build-script and proc-macro dependency whose features vary;
- `[workspace.dependencies]` declares `test-unify` and each narrow third-party crate once.

This tool owns all three: `--fix` removes and regenerates them, so do not edit them by hand.
CI runs the check when a manifest changes; when it fails, run `--fix`, which takes a few minutes.
"""

import argparse
import concurrent.futures
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNIFY = "test-unify"
UNIFY_DIR = ROOT / "crates" / UNIFY
TABLE = "[target.'cfg(all())'.dev-dependencies]"
TABLE_NOTE = (
    "# Generated by tools/check-feature-unification.py --fix (do not edit): the features\n"
    "# `cargo test --workspace` resolves for crates these tests build, so `cargo test -p`\n"
    "# builds them identically.\n"
)
BEGIN = "# Begin generated declarations (tools/check-feature-unification.py --fix; do not edit)."
END = "# End generated declarations."
WIDE_SHARE = 0.5
TREE_LINE = re.compile(r"^(?P<prefix>[ |`-]*)(?P<body>.*)$")


def cargo(*args):
    result = subprocess.run(["cargo", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if result.returncode:
        sys.exit(f"cargo {' '.join(args)} failed:\n{result.stderr}")
    return result.stdout


def host_triple():
    version = subprocess.run(["rustc", "-vV"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return next(line.split(": ", 1)[1] for line in version.splitlines() if line.startswith("host: "))


def resolve(selection, triple):
    """{(name, version, side): features} for a selection's test build; side is host or target.

    An explicit target keeps a crate's host and target builds apart, so `cargo tree` prints the
    subtree of each instead of eliding the second as a repeat.
    """
    text = cargo("tree", *selection, "--locked", "--target", triple, "-e", "normal,build,dev",
                 "--prefix", "indent", "--charset", "ascii", "-f", "{p}|{f}")
    nodes = {}
    stack = []
    headings = {}
    for line in text.splitlines():
        if not line.strip():
            stack.clear()
            headings.clear()
            continue
        prefix, body = TREE_LINE.match(line).groups()
        depth = len(prefix) // 4
        if body.startswith("["):
            headings[depth] = body
            continue
        while stack and stack[-1][0] >= depth:
            stack.pop()
        for stale in [d for d in headings if d >= depth]:
            del headings[stale]
        host = (bool(stack) and (stack[-1][1] or stack[-1][2])) or headings.get(depth - 1) == "[build-dependencies]"
        spec, _, features = body.partition("|")
        words = spec.split()
        macro = "(proc-macro)" in spec
        key = (words[0], words[1].removeprefix("v"), "host" if host or macro else "target")
        nodes.setdefault(key, set()).update(f for f in features.replace("(*)", "").strip().split(",") if f)
        stack.append((depth, host, macro))
    return nodes


def metadata():
    """Members by name and the resolved package graph by (name, version).

    Each member gets `direct`: {(package, version): the key its manifests name it by}. Each graph
    entry holds its `features` table and `deps`: {manifest key: ((name, version), built for host)}.
    """
    meta = json.loads(cargo("metadata", "--format-version", "1"))
    packages = {p["id"]: p for p in meta["packages"]}
    members = {packages[i]["name"]: packages[i] for i in meta["workspace_members"]}
    graph = {}
    for node in meta["resolve"]["nodes"]:
        package = packages[node["id"]]
        keys = {(d.get("rename") or d["name"]).replace("-", "_"): d.get("rename") or d["name"]
                for d in package["dependencies"]}
        deps = {}
        for dep in node["deps"]:
            target = packages[dep["pkg"]]
            macro = any("proc-macro" in t["kind"] for t in target["targets"])
            build = all(kind["kind"] == "build" for kind in dep["dep_kinds"])
            deps[keys.get(dep["name"], dep["name"])] = ((target["name"], target["version"]), macro or build)
        graph[package["name"], package["version"]] = {"features": package["features"], "deps": deps}
        if node["id"] in meta["workspace_members"]:
            package["direct"] = {key_target[0]: key for key, key_target in deps.items()}
    return members, graph


def scan():
    members, graph = metadata()
    triple = host_triple()
    selections = [("--workspace",)] + [("-p", name) for name in members]
    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        resolved = dict(zip(selections, pool.map(lambda s: resolve(s, triple), selections)))
    return members, graph, resolved[("--workspace",)], {s[1]: resolved[s] for s in selections[1:]}


def differences(workspace, selections):
    """{member: {node: features its test build lacks}} and the nodes the workspace never resolves.

    Without `--target`, Cargo builds a crate the build resolves for both the host and the target
    with the same features once, with the target's profile, and build scripts and proc-macros
    link that build. A selection that builds such a crate only for the host builds it with the
    build-script profile instead, and so rebuilds every proc-macro and build script above it.
    Its missing target build therefore counts as lacking all the target build's features.
    """
    shared = {(n, v) for n, v, side in workspace
              if side == "host" and workspace.get((n, v, "target")) == workspace[n, v, side]}
    lacking, unknown = {}, {}
    for member, nodes in selections.items():
        for node, features in nodes.items():
            if node not in workspace:
                unknown.setdefault(node, []).append(member)
            elif workspace[node] - features:
                lacking.setdefault(member, {})[node] = workspace[node] - features
            if node[2] == "host" and node[:2] in shared and (*node[:2], "target") not in nodes:
                lacking.setdefault(member, {})[(*node[:2], "target")] = workspace[(*node[:2], "target")] or {""}
    return lacking, unknown


def report(lacking, unknown):
    by_node = {}
    for member, nodes in lacking.items():
        for node, missing in nodes.items():
            by_node.setdefault(node, []).append((member, missing))
    for (name, version, side), rows in sorted(by_node.items()):
        missing = sorted(set().union(*(m for _, m in rows)) - {""})
        what = f"lacks {', '.join(missing)}" if missing else "has no target build"
        examples = ", ".join(sorted(member for member, _ in rows)[:4])
        print(f"{name} {version} ({side}) {what} in {len(rows)} member test builds, e.g. {examples}")
    for (name, version, side), owners in sorted(unknown.items()):
        print(f"note: {name} {version} ({side}) appears in {', '.join(sorted(owners)[:4])} but not in the "
              "workspace's resolution; `cargo tree` elided it there, so it is not compared")


def toml_list(items):
    return "[" + ", ".join(f'"{item}"' for item in sorted(items)) + "]"


def third_party_spec(name, version, features):
    package = f'package = "{name}", ' if name else ""
    version = version.split("+")[0]
    return f'{{ {package}version = "{version}", default-features = false, features = {toml_list(features)} }}'


def keyed(nodes):
    """Dependency keys for third-party nodes: the crate name, plus its version where two share it."""
    names = {}
    for name, version, _ in nodes:
        names.setdefault(name, set()).add(version)
    keys = {}
    for node in nodes:
        name, version, _ = node
        if len(names[name]) == 1:
            keys[node] = name
        else:
            major, minor = version.split(".")[:2]
            keys[node] = f"{name}-{major if major != '0' else '0-' + minor}"
    return keys


def strip_member(path):
    text = path.read_text(encoding="utf-8")
    start = text.find(TABLE_NOTE)
    if start < 0:
        return
    end = text.find("\n[", start + len(TABLE_NOTE) + len(TABLE))
    path.write_text(text[:start].rstrip("\n") + "\n" + (text[end:] if end >= 0 else ""), encoding="utf-8", newline="\n")


def write_member(path, entries):
    strip_member(path)
    if not entries:
        return
    text = path.read_text(encoding="utf-8").rstrip("\n")
    lines = [f"{key} = {spec}" for key, spec in sorted(entries.items())]
    path.write_text(f"{text}\n\n{TABLE_NOTE}{TABLE}\n" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_workspace(declarations):
    path = ROOT / "Cargo.toml"
    text = path.read_text(encoding="utf-8")
    if BEGIN in text:
        start, end = text.index(BEGIN), text.index(END) + len(END) + 1
        text = text[:start] + text[end:]
    if declarations:
        block = BEGIN + "\n" + "".join(f"{key} = {spec}\n" for key, spec in sorted(declarations.items())) + END + "\n"
        header = text.index("[workspace.dependencies]\n") + len("[workspace.dependencies]\n")
        text = text[:header] + block + text[header:]
    path.write_text(text, encoding="utf-8", newline="\n")


def write_unify(target, host):
    manifest = [
        "# Generated by tools/check-feature-unification.py --fix (do not edit). Each member whose",
        "# tests build one of these crates dev-depends on this package, so its test build resolves",
        "# them with the features `cargo test --workspace` resolves; build-dependencies reach",
        "# build scripts and proc-macros.",
        "[package]",
        f'name = "{UNIFY}"',
        *(f"{field}.workspace = true" for field in ("version", "edition", "rust-version", "publish", "license")),
        "",
        "[lib]",
        "test = false",
        "doctest = false",
    ]
    keys = keyed(target | host)
    for table, nodes in (("dependencies", target), ("build-dependencies", host)):
        manifest += ["", f"[{table}]"]
        manifest += [f"{keys[n]} = {third_party_spec(n[0] if keys[n] != n[0] else '', n[1], f)}"
                     for n, f in sorted(nodes.items())]
    (UNIFY_DIR / "src").mkdir(parents=True, exist_ok=True)
    (UNIFY_DIR / "Cargo.toml").write_text("\n".join(manifest) + "\n", encoding="utf-8", newline="\n")
    (UNIFY_DIR / "build.rs").write_text(
        "// Cargo builds this package's build-dependencies, and so unifies their features with every\n"
        "// other build script's and proc-macro's, only for a package with a build script.\n"
        "fn main() {\n    println!(\"cargo:rerun-if-changed=build.rs\");\n}\n", encoding="utf-8", newline="\n")
    (UNIFY_DIR / "src" / "lib.rs").write_text(
        "//! Dev-only feature union; see tools/check-feature-unification.py. It has no code.\n",
        encoding="utf-8", newline="\n")


def strip():
    for manifest in (ROOT / "crates").glob("*/Cargo.toml"):
        strip_member(manifest)
    write_workspace({})
    write_unify({}, {})


def implied(graph, chosen):
    """(node, feature) pairs that enabling `chosen` {node: features} turns on through feature forwards."""
    on = set()
    stack = [(node, f) for node, features in chosen.items() for f in features]
    while stack:
        node, feature = stack.pop()
        name, version, side = node
        if (node, feature) in on or (name, version) not in graph:
            continue
        on.add((node, feature))
        package = graph[name, version]
        for item in package["features"].get(feature, []):
            if item.startswith("dep:"):
                continue
            if "/" in item:
                key, forwarded = item.split("/", 1)
                dependency = package["deps"].get(key.rstrip("?"))
                if dependency:
                    (dep_name, dep_version), host = dependency
                    stack.append(((dep_name, dep_version, "host" if host else side), forwarded))
            else:
                stack.append((node, item))
    return on


def member_spec(members, shared, owner, name, features):
    if name in shared:
        source = "workspace = true"
    else:
        target = Path(members[name]["manifest_path"]).parent
        here = Path(members[owner]["manifest_path"]).parent
        source = f'path = "{Path(os.path.relpath(target, here)).as_posix()}"'
    return f"{{ {source}, features = {toml_list(features)} }}"


def fix():
    strip()
    shared = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))["workspace"]["dependencies"]
    crates = {}
    narrow = {}
    unify_target, unify_host, declared = {}, {}, {}
    for round_ in range(1, 30):
        members, graph, workspace, selections = scan()
        lacking, unknown = differences(workspace, selections)
        print(f"round {round_}: {sum(len(n) for n in lacking.values())} differences in {len(lacking)} member test builds")
        if not lacking:
            report({}, unknown)
            return True
        state = lambda: repr((sorted(unify_target), sorted(unify_host), crates, narrow))
        before = state()
        share = {node: sum(node in s or node in lacking.get(m, ()) for m, s in selections.items()) / len(selections)
                 for nodes in lacking.values() for node in nodes}
        for node in {node for nodes in lacking.values() for node in nodes if node[0] not in members}:
            if node[2] == "host":
                unify_host[node] = workspace[node]
            elif share[node] >= WIDE_SHARE:
                unify_target[node] = workspace[node]
        unified = unify_target | unify_host
        for skip_implied in (True, False):
            for member, nodes in lacking.items():
                reach = {node: len(implied(graph, {node: workspace[node]})) for node in nodes}
                chosen = dict(unified)
                for node in sorted(nodes, key=lambda n: (-reach[n], n)):
                    if node in unified:
                        continue
                    if skip_implied and all((node, f) in implied(graph, chosen) for f in nodes[node]):
                        continue
                    chosen[node] = workspace[node]
                    if node[0] in members:
                        crates.setdefault(member, {})[node[0]] = workspace[node]
                    else:
                        declared[node] = workspace[node]
                        narrow.setdefault(member, set()).add(node)
            if state() != before:
                break
        else:
            report(lacking, unknown)
            return False
        keys = {node: f"unify-{key}" for node, key in keyed(declared).items()}
        write_workspace({UNIFY: f'{{ path = "crates/{UNIFY}" }}'} |
                        {keys[n]: third_party_spec(n[0], n[1], f) for n, f in declared.items()})
        write_unify(unify_target, unify_host)
        unified = set(unify_target) | set(unify_host)
        for member, nodes in selections.items():
            generated = {members[member]["direct"].get((name, members[name]["version"]), name):
                         member_spec(members, shared, member, name, f) for name, f in crates.get(member, {}).items()}
            for node in narrow.get(member, ()):
                key = members[member]["direct"].get(node[:2])
                key = None if key == keys[node] else key
                generated[key or keys[node]] = (
                    third_party_spec(node[0] if key != node[0] else "", node[1], declared[node]) if key
                    else "{ workspace = true }")
            if member != UNIFY and unified & (nodes.keys() | lacking.get(member, {}).keys()):
                generated[UNIFY] = "{ workspace = true }"
            write_member(Path(members[member]["manifest_path"]), generated)
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--fix", action="store_true", help="regenerate the dev-dependencies until none differ")
    args = parser.parse_args()
    if args.fix:
        sys.exit(0 if fix() else 1)
    members, _, workspace, selections = scan()
    lacking, unknown = differences(workspace, selections)
    report(lacking, unknown)
    if lacking:
        print("Run `python tools/check-feature-unification.py --fix`.")
        sys.exit(1)
    print(f"Every member's test build resolves the workspace's features ({len(members)} members).")


if __name__ == "__main__":
    main()
