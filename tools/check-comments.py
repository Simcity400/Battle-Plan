@cache
def parser_for(language):
    return get_parser(language)


@cache
def query_for(language, pattern):
    return Query(parser_for(language).language, pattern)


def captures(language, pattern, root, name):
    return QueryCursor(query_for(language, pattern)).captures(root).get(name, ())


def comment_spans(language, source, workflow=False):
    if language in ("hash", "nsis"):
        pattern = HASH_COMMENT if language == "hash" else NSIS_TOKEN
        return [match.span(1) for match in pattern.finditer(source) if match[1] is not None]

    root = parser_for(language).parse(source).root_node
    spans = [(node.start_byte, node.end_byte) for node in captures(
        language, COMMENT_NODES.get(language, "(comment) @comment"), root, "comment",
    )]
    if language == "html":
        for tag, embedded in (("script", "javascript"), ("style", "css")):
            pattern = f"({tag}_element (raw_text) @body)"
            for body in captures(language, pattern, root, "body"):
                start = body.parent.child_by_field_name("start_tag") or body.parent.named_children[0]
                type_attribute = re.search(rb'''\btype\s*=\s*['"]([^'"]+)['"]''', start.text, re.I)
                types = (b"module", b"text/javascript", b"application/javascript") if tag == "script" else (b"text/css",)
                if type_attribute is None or type_attribute[1].lower() in types:
                    spans.extend((body.start_byte + a, body.start_byte + b) for a, b in comment_spans(embedded, body.text))
    if workflow:
        spans.extend(workflow_comments(root, source))
    return sorted(spans)


def yaml_value(mapping, key):
    if mapping is None:
        return None
    for pair in mapping.named_children:
        name = pair.child_by_field_name("key")
        if name is not None and name.text.strip(b"'\"") == key:
            value = pair.child_by_field_name("value")
            return next((node for node in value.named_children if node.type != "comment"), None) if value is not None else None
    return None


def workflow_comments(root, source):
    def default_shell(mapping):
        return yaml_value(yaml_value(yaml_value(mapping, b"defaults"), b"run"), b"shell")

    top = "(document (block_node (block_mapping) @workflow))"
    steps = "(block_sequence_item (block_node (block_mapping) @step))"
    for workflow in captures("yaml", top, root, "workflow"):
        jobs = yaml_value(workflow, b"jobs")
        if jobs is None:
            continue
        for pair in jobs.named_children:
            value = pair.child_by_field_name("value")
            if value is None or not value.named_children:
                continue
            job = value.named_children[0]
            sequence = yaml_value(job, b"steps")
            if sequence is None or sequence.type != "block_sequence":
                continue
            runner = yaml_value(job, b"runs-on")
            default = "powershell" if runner is not None and b"windows" in runner.text.lower() else "bash"
            for step in captures("yaml", steps, sequence, "step"):
                scalar = yaml_value(step, b"run")
                if scalar is None or scalar.type != "block_scalar":
                    continue
                shell = yaml_value(step, b"shell") or default_shell(job) or default_shell(workflow)
                command = shell.text.strip(b"'\"").split() if shell is not None else []
                language = SHELLS.get(command[0], default) if command else default
                yield from script_comments(language, source, scalar)


def script_comments(language, source, scalar):
    start = source.find(b"\n", scalar.start_byte, scalar.end_byte) + 1
    if start == 0:
        return
    lines = source[start:scalar.end_byte].splitlines(keepends=True)
    indent = min((len(line) - len(line.lstrip(b" ")) for line in lines if line.strip()), default=0)
    script, source_offsets, script_offsets = [], [], []
    source_offset, script_offset = start, 0
    for line in lines:
        prefix = min(indent, len(line) - len(line.lstrip(b" ")))
        script.append(line[prefix:])
        source_offsets.append(source_offset + prefix)
        script_offsets.append(script_offset)
        source_offset += len(line)
        script_offset += len(line) - prefix
    script_text = re.sub(rb"\$\{\{[^\r\n]*?\}\}", lambda match: b"x" * len(match[0]), b"".join(script))
    for begin, end in comment_spans(language, script_text):
        first = bisect_right(script_offsets, begin) - 1
        last = bisect_right(script_offsets, end - 1) - 1
        yield source_offsets[first] + begin - script_offsets[first], source_offsets[last] + end - script_offsets[last]


def exempt(name, start, comment, source=b""):
    if start == 0 and comment.startswith(b"#!/") and language_of(name) in ("bash", "python"):
        return True
    if start == 0 and name.endswith(".ps1") and re.match(rb"<#[ \t]*\n[ \t]*\.SYNOPSIS[ \t]*\n", comment, re.I):
        return True
    if (name.endswith("/Cargo.toml") or name == "Cargo.toml") and comment in CARGO_GENERATED:
        return True
    if re.fullmatch(rb"// quarantine: #[1-9][0-9]* \S.*", comment):
        if name.endswith(".rs"):
            return True
        following = source[start + len(comment):].lstrip(b"\r\n").split(b"\n", 1)[0]
        return bool(re.search(r"\.test\.[cm]?[jt]sx?$", name)) and b"test.skip(" in following
    if name.startswith(".github/workflows/") and re.fullmatch(rb"# v\d+(?:\.\d+)*", comment):
        line = source[source.rfind(b"\n", 0, start) + 1:start]
        return bool(re.fullmatch(rb"\s*(?:- )?uses: [\w.-]+/[\w./-]+@[0-9a-f]{40}\s+", line))
    return bool(re.fullmatch(rb"(?:#|//|/\*)\s*SPDX-License-Identifier: [\w.+() -]+(?:\*/)?", comment))


SAFETY_COMMENT = re.compile(rb"// SAFETY: \S")
SAFETY_HEADING = re.compile(rb" {0,3}#[ \t]+Safety[ \t]*#*[ \t]*")
UNSAFE_ATTRIBUTE = re.compile(rb"#?\[\s*unsafe\s*\(")
FENCE = re.compile(rb" {0,3}(`{3,}|~{3,})(.*)")
NOT_UNSAFE_SITES = {"function_item", "function_signature_item", "mod_item", "struct_item", "enum_item",
                    "union_item", "trait_item", "macro_definition"}
UNSAFE_ITEMS = {"function_item", "function_signature_item", "trait_item", "impl_item"}
TOKEN_QUALIFIERS = {b"pub", b"const", b"async", b"unsafe", b"extern", b"default"}
TOKEN_ITEMS = {b"fn", b"mod", b"struct", b"enum", b"union", b"trait", b"impl", b"type", b"macro_rules"}
CONTINUATIONS = {b"else", b".", b"?", b"as", b"=", b"=>", b"+", b"-", b"*", b"/", b"%", b"==", b"!=", b"<", b">", b"<=",
                 b">=", b"&&", b"||", b"&", b"|", b"^", b".."}


def comment_run(node, kind):
    run = [node]
    while (after := run[-1].next_sibling) is not None and kind(after) and after.start_point[0] == run[-1].start_point[0] + 1:
        run.append(after)
    return run


def adjacent_code(last, past=None):
    """The code on the line after the comment `last`, past attributes on the lines that follow (or on
    the attribute's own line); None when a blank line or another comment comes first. `past` names
    the other kind of safety contract that may sit between: "safety" passes a `// SAFETY:` run (for
    one on an unsafe attribute), "docs" passes a `///` run."""
    rows, node, in_safety = (last.start_point[0] + 1,), last.next_sibling, False
    while node is not None and node.start_point[0] in rows:
        attribute = node.next_sibling if node.type == "#" else None
        plain = node.type == "line_comment" and not node.text.startswith((b"///", b"//!"))
        if node.type == "attribute_item":
            end, in_safety = node.end_point[0], False
        elif attribute is not None and attribute.type == "token_tree" and attribute.text.startswith(b"["):
            end, node, in_safety = attribute.end_point[0], attribute, False
        elif past == "safety" and plain and (in_safety or SAFETY_COMMENT.match(node.text)):
            end, in_safety = node.start_point[0], True
        elif past == "docs" and node.type == "line_comment" and node.text.startswith(b"///"):
            end = node.start_point[0]
        elif node.type in ("line_comment", "block_comment"):
            return None
        else:
            return node
        rows, node = (end, end + 1), node.next_sibling
    return None


def has_unsafe(node):
    """Whether `node` holds an unsafe operation, block or item; `unsafe fn` types and pointers are not."""
    if node.type == "function_type":
        return False
    if node.type == "unsafe":
        following = node.next_sibling
        if in_macro(node) and following is not None and following.text == b"extern":
            following = following.next_sibling
            if following is not None and following.type == "string_literal":
                following = following.next_sibling
        return not (in_macro(node) and following is not None and following.text == b"fn")
    return node.type == "unsafe_block" or any(has_unsafe(child) for child in node.children)


def unsafe_attribute(last, code):
    """Whether an `#[unsafe(...)]` attribute sits between the comment `last` and `code`."""
    node = last.next_sibling
    while node is not None and node.start_byte < code.start_byte:
        if node.type in ("attribute_item", "token_tree") and UNSAFE_ATTRIBUTE.match(node.text):
            return True
        node = node.next_sibling
    return False


def in_macro(node):
    return node.parent is not None and node.parent.type in ("token_tree", "token_repetition")


def braces(node):
    return node.type == "token_tree" and node.text.startswith(b"{")


def token_item(node):
    """For tokens in a macro body: the item keyword the tokens at `node` declare, and whether
    `unsafe` qualifies it; (None, False) when they begin no item. A metavariable directly before a
    qualifier or item keyword, such as `$vis`, can only be a visibility."""
    qualified = False
    while node is not None and (node.text in TOKEN_QUALIFIERS or node.type == "string_literal"
                                or node.type == "token_tree" and node.prev_sibling is not None and node.prev_sibling.text == b"pub"
                                or node.type == "metavariable" and node.next_sibling is not None
                                and node.next_sibling.text in TOKEN_QUALIFIERS | TOKEN_ITEMS):
        qualified = qualified or node.text == b"unsafe"
        node = node.next_sibling
    return (node.text.decode(), qualified) if node is not None and node.text in TOKEN_ITEMS else (None, False)


def foreign_block(tree):
    """Whether the macro-body token tree `tree` is the braces of an `unsafe extern "ABI" { ... }`
    block, whose functions are unsafe to call unless declared `safe fn`."""
    before = tree.prev_sibling if braces(tree) else None
    if before is not None and before.type == "string_literal":
        before = before.prev_sibling
    return before is not None and before.text == b"extern" and before.prev_sibling is not None and before.prev_sibling.text == b"unsafe"


def inside_unsafe(node):
    """Whether `node` sits in an `unsafe` block, short of an enclosing function or closure."""
    node = node.parent
    while node is not None and node.type not in ("function_item", "closure_expression"):
        if node.type == "unsafe_block":
            return True
        node = node.parent
    return False


def unsafe_operation(node):
    """Whether `node` dereferences or calls, the two kinds of operation an `unsafe` block's statement
    can owe its contract to. Without types, a raw pointer can't be told from a reference."""
    if node.type == "unary_expression" and node.child_count == 2 and node.children[0].type == "*":
        return True
    return node.type == "call_expression" or any(unsafe_operation(child) for child in node.children)


DEREFERENCE_AFTER = {b"=", b"(", b",", b";", b"{", b"&", b"!", b"*", b"=>", b"return", b"mut"}


def unsafe_tokens(node):
    """Whether macro tokens at `node` sit in an `unsafe { ... }` token tree."""
    tree = node.parent
    while tree is not None and tree.type in ("token_tree", "token_repetition"):
        if braces(tree) and tree.prev_sibling is not None and tree.prev_sibling.text == b"unsafe":
            return True
        tree = tree.parent
    return False


TYPE_TOKENS = {b"*", b"const", b"mut", b"::", b"<", b">", b"&", b"dyn", b"()"}


def token_operation(node):
    """Whether the macro statement starting at `node` dereferences or calls, up to the `;` or `,`
    that ends it, or the `{...}` body that closes it. A `let` pattern and a cast's type are
    skipped, since `Some(value)` and `*mut T` there are neither calls nor dereferences."""
    unit, pattern, cast = node, node.text == b"let", False
    while unit is not None and unit.type not in (";", ","):
        text = unit.text
        if text == b"let":
            pattern = True
        elif pattern:
            pattern = text != b"="
        elif cast and (text in TYPE_TOKENS or unit.type in ("identifier", "primitive_type")):
            pass
        elif text == b"as":
            cast = True
        else:
            cast = False
            if tokens_operate(unit):
                return True
            if braces(unit) and (unit.next_sibling is None or unit.next_sibling.text not in CONTINUATIONS):
                return False
        unit = unit.next_sibling
    return False


def tokens_operate(unit):
    """Whether the token `unit` is a dereferencing `*` or a call's `(` group, or, as a group, holds one."""
    previous = unit.prev_sibling
    if unit.text == b"*":
        if previous is None or previous.type in ("line_comment", "block_comment"):
            return True
        if previous.text == b"mut":
            return previous.prev_sibling is not None and previous.prev_sibling.text == b"&"
        return previous.text in DEREFERENCE_AFTER
    if unit.type == "token_tree":
        if unit.text.startswith(b"(") and previous is not None and previous.type in ("identifier", "metavariable", ">"):
            return True
        children = unit.children[1:-1]
        if not (braces(unit) and any(child.text == b"=>" for child in children)):
            return any(tokens_operate(child) for child in children)
        pattern = True
        for child in children:
            if pattern:
                pattern = child.text not in (b"=>", b"if")
            elif child.text == b",":
                pattern = True
            elif tokens_operate(child):
                return True
            elif braces(child):
                pattern = True
        return False
    return False


def unsafe_site(node):
    if node.type == "." and node.parent.type == "field_expression":
        call = node.parent.parent
        if call is not None and call.type == "generic_function":
            call = call.parent
        if call is not None and call.type == "call_expression":
            arguments = call.child_by_field_name("arguments")
            return arguments is not None and has_unsafe(arguments) or inside_unsafe(call)
    if node.type in NOT_UNSAFE_SITES:
        return False
    if node.type == "impl_item":
        return unsafe_item(node)
    if node.is_named and not in_macro(node) and inside_unsafe(node) and unsafe_operation(node):
        return True
    if node.is_named and not in_macro(node):
        return has_unsafe(node)
    if in_macro(node):
        item, qualified = token_item(node)
        if item is not None:
            return item == "impl" and qualified
        if unsafe_tokens(node) and token_operation(node):
            return True
    unit, generics, in_type = node, 0, False
    while unit is not None and unit.type != ";" and (unit.type != "," or generics):
        if has_unsafe(unit):
            return True
        if unit.text == b"->" or unit.text == b":" and node.text == b"let":
            in_type = True
        elif unit.text == b"=" and not generics:
            in_type = False
        if unit.text == b"<" and unit.prev_sibling is not None and (unit.prev_sibling.text == b"::" or generics or in_type):
            generics += 1
        elif unit.text in (b">", b">>") and generics:
            generics = max(0, generics - len(unit.text))
        elif braces(unit) and (unit.next_sibling is None or unit.next_sibling.text not in CONTINUATIONS):
            return False
        unit = unit.next_sibling
    return False


def unsafe_item(node):
    if node is None:
        return False
    if in_macro(node):
        item, qualified = token_item(node)
        tree = node.parent.parent if node.parent.type == "token_repetition" else node.parent
        return item in ("fn", "trait", "impl") and (qualified or item == "fn" and foreign_block(tree))
    if node.type == "function_signature_item" and node.parent.parent is not None and node.parent.parent.type == "foreign_mod_item":
        return not any(child.type == "ERROR" and child.text == b"safe" for child in node.children)
    return node.type in UNSAFE_ITEMS and any(
        child.type == "unsafe" or child.type == "function_modifiers" and has_unsafe(child) for child in node.children
    )


def safety_heading(run):
    """Whether the doc run has a `# Safety` heading outside Markdown code (not in a fenced block and
    not indented as code) with a contract under it, before the next heading or the run's end."""
    fence, section = None, False
    for comment in run:
        text = comment.text[3:].rstrip(b"\r\n")
        text = text[1:] if text.startswith(b" ") else text
        opening = FENCE.fullmatch(text)
        if fence is not None:
            if opening and opening[1][0] == fence[0] and len(opening[1]) >= len(fence) and not opening[2].strip():
                fence = None
            elif section:
                return True
        elif opening:
            fence = opening[1]
            if section:
                return True
        elif SAFETY_HEADING.fullmatch(text):
            section = True
        elif section and re.match(rb" {0,3}#", text):
            section = False
        elif section and text.strip():
            return True
    return False


def safety_contracts(source):
    """Comment spans exempt as safety contracts: a `// SAFETY:` run directly before code that
    contains an `unsafe` block, keyword or impl, and a `///` run with a `# Safety` heading directly
    on an unsafe function, trait or impl."""
    if b"SAFETY" not in source and b"Safety" not in source:
        return set()
    plain = lambda node: node.type == "line_comment" and not node.text.startswith((b"///", b"//!"))
    outer = lambda node: node.type == "line_comment" and node.text.startswith(b"///") and not node.text.startswith(b"////")
    exempt_spans = set()
    for node in captures("rust", "(line_comment) @comment", parser_for("rust").parse(source).root_node, "comment"):
        previous = node.prev_sibling
        if plain(node) and SAFETY_COMMENT.match(node.text):
            if source[source.rfind(b"\n", 0, node.start_byte) + 1:node.start_byte].strip():
                continue
            run = comment_run(node, lambda after: plain(after) and not SAFETY_COMMENT.match(after.text))
            code = adjacent_code(run[-1], past="docs")
            if code is not None and (unsafe_site(code) or unsafe_attribute(run[-1], code)):
                exempt_spans.update((comment.start_byte, comment.end_byte) for comment in run)
        elif outer(node) and not (previous is not None and outer(previous) and previous.start_point[0] == node.start_point[0] - 1):
            run = comment_run(node, outer)
            if safety_heading(run) and unsafe_item(adjacent_code(run[-1], past="safety")):
                exempt_spans.update((comment.start_byte, comment.end_byte) for comment in run)
    return exempt_spans


def comments(name, source):
    language = language_of(name)
    if language is None:
        return []
    spans = comment_spans(language, source, workflow=name.startswith(".github/workflows/") and language == "yaml")
    contracts = safety_contracts(source) if language == "rust" else set()
    return [(a, b) for a, b in spans if (a, b) not in contracts and not exempt(name, a, source[a:b], source)]


def added_comments(name, before, after, old_name=None):
    previous = Counter(before[a:b] for a, b in comments(old_name or name, before))
    for start, end in comments(name, after):
        body = after[start:end]
        if previous[body]:
            previous[body] -= 1
        else:
            yield after.count(b"\n", 0, start) + 1


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=True).stdout


def paths(*args):
    return git(*args).decode("utf-8").rstrip("\0").split("\0")


def changes(base):
    fields = iter(paths("diff", "--name-status", "-z", "-M", "--diff-filter=ACMRT", base, "--"))
    changed = {}
    for status in filter(None, fields):
        old = next(fields)
        name = next(fields) if status[0] in "RC" else old
        changed[name] = old if status[0] in "MRT" and language_of(old) else None
    for name in filter(None, paths("ls-files", "--others", "--exclude-standard", "-z")):
        changed.setdefault(name, None)
    return sorted(changed.items())


def read_source(name):
    return (ROOT / name).read_bytes().replace(b"\r\n", b"\n")


def check(base):
    failed = False
    for name, old in changes(base):
        if not language_of(name):
            continue
        before = git("show", f"{base}:{old}").replace(b"\r\n", b"\n") if old is not None else b""
        for line in added_comments(name, before, read_source(name), old):
            print(f"{name}:{line}: new comment. Remove it or record the decision in docs/adr/.")
            failed = True
    return int(failed)


def comment_lines(source, spans):
    lines = set()
    chunks = []
    previous = line = 0
    for start, end in spans:
        code = source[previous:start]
        line += code.count(b"\n")
        height = source.count(b"\n", start, end)
        lines.update(range(line, line + height + int(source[end - 1] != 10)))
        chunks.extend((code, b"\n" * height))
        line += height
        previous = end
    chunks.append(source[previous:])
    stripped = b"".join(chunks).split(b"\n")
    return len(lines), sum(not stripped[line].strip() for line in lines)


def inventory(show, selected):
    totals = defaultdict(Counter)
    names = paths("ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", *selected)
    for name in sorted(set(names) - {""}):
        if not language_of(name) or not (ROOT / name).is_file():
            continue
        source = read_source(name)
        spans = comments(name, source)
        if show:
            for start, end in spans:
                line = source.count(b"\n", 0, start) + 1
                print(f"{name}:{line}: {source[start:end].decode('utf-8', errors='replace')!a}")
        touched, standalone = comment_lines(source, spans)
        totals[language_of(name)].update(files=1, comments=len(spans), lines=touched, standalone=standalone)
    if not show:
        print(f"{'Language':<15} {'Files':>6} {'Comments':>9} {'Lines':>9} {'Comment-only':>13}")
        for language, counts in sorted(totals.items()) + [("Total", sum(totals.values(), Counter()))]:
            print(f"{language:<15} {counts['files']:>6} {counts['comments']:>9} {counts['lines']:>9} {counts['standalone']:>13}")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Ban new source comments and inventory existing ones.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--against", metavar="REF", help="compare changes with a Git revision")
    mode.add_argument("--count", action="store_true", help="count comment tokens and physical lines")
    mode.add_argument("--list", action="store_true", help="list comments with their file and line")
    parser.add_argument("paths", nargs="*", metavar="PATH", help="limit inventory to Git pathspecs")
    args = parser.parse_args()
    if args.against is not None and args.paths:
        parser.error("paths only apply to --count and --list")
    try:
        return check(args.against) if args.against is not None else inventory(args.list, args.paths)
    except subprocess.CalledProcessError as error:
        print(error.stderr.decode("utf-8", errors="replace"), file=sys.stderr, end="")
        return 1


if __name__ == "__main__":
    sys.exit(main())
