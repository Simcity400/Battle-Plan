/// Which declared block of a family a [`CallerDefect`] is about.
///
/// **This enum is a drift boundary.** A tenth family with a new block shape adds
/// an arm here and is a compile error at every site's formatter.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum TrailerBlock {
    /// The family's uniform rows.
    Rows,
    /// `MTRR`'s resource-identity block.
    Identities,
    /// `MTRD`'s country witnesses.
    Witnesses,
    /// `MTRD` v3/v4's incomplete-owner block.
    IncompleteOwners,
    /// `MTS1`'s country segment.
    Countries,
    /// `MTS1`'s item segment.
    Items,
}

impl TrailerBlock {
    pub const ALL: [TrailerBlock; 6] = [
        TrailerBlock::Rows,
        TrailerBlock::Identities,
        TrailerBlock::Witnesses,
        TrailerBlock::IncompleteOwners,
        TrailerBlock::Countries,
        TrailerBlock::Items,
    ];

    /// The name a site's formatter spells. Generated by an exhaustive `match`
    /// with no wildcard arm.
    pub const fn name(self) -> &'static str {
        match self {
            TrailerBlock::Rows => "rows",
            TrailerBlock::Identities => "identities",
            TrailerBlock::Witnesses => "witnesses",
            TrailerBlock::IncompleteOwners => "incomplete owners",
            TrailerBlock::Countries => "countries",
            TrailerBlock::Items => "items",
        }
    }

    /// This block's position in [`TrailerBlock::ALL`], by an exhaustive `match`
    /// with no wildcard arm.
    const fn ordinal(self) -> usize {
        match self {
            TrailerBlock::Rows => 0,
            TrailerBlock::Identities => 1,
            TrailerBlock::Witnesses => 2,
            TrailerBlock::IncompleteOwners => 3,
            TrailerBlock::Countries => 4,
            TrailerBlock::Items => 5,
        }
    }
}

/// `TrailerBlock::ALL` is exactly the ordinals, in order, at BUILD time.
///
/// WHAT THIS CATCHES: an arm added to `ALL` that `ordinal` does not know (a
/// compile error, because `ordinal`'s `match` has no wildcard), `ALL` reordered,
/// `ALL` carrying a duplicate, and `ALL` carrying an arm twice while missing
/// another.
///
/// WHAT IT CANNOT CATCH FROM IN HERE: a seventh arm added to the enum and to
/// `ordinal` but never put in `ALL`. Proving "every variant is in `ALL`" needs
/// `variant_count` (unstable) or a derive macro, and this leaf may have neither
/// -- no dependencies, and no `macro_rules!`, because the leaf seal refuses
/// both. That hole is the same one every `ALL` table in every leaf carries, and
/// it is CLOSED FROM OUTSIDE, in the gate that already reads this crate's
/// source: `verify_world_fold_citations.py::verify_leaf_all_tables_are_complete`
/// refuses any leaf whose `pub enum` has an `ALL` table that omits one of its
/// variants. Proof in `runs/kw_d43_rewire/all_table_proof.txt`, including the
/// sharp case where the declared length is decremented too.
///
/// The test that consumes this one ALSO matches on the enum exhaustively, so an
/// added arm is a compile error there as well.
const _: () = {
    let mut i = 0;
    while i < TrailerBlock::ALL.len() {
        if TrailerBlock::ALL[i].ordinal() != i {
            panic!("d43_grammar: TrailerBlock::ALL is not its own ordinals, in order");
        }
        i += 1;
    }
};

/// A defect in the CALLER, not in the payload.
///
/// Kept apart from every other [`ViolationKind`] arm because the operands
/// describe a program that walked wrong, not a capture that is malformed, and a
/// site that folded the two together would report a broken recorder as a broken
/// game.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CallerDefect {
    /// [`TrailerCursor::read_body`] was called without a delimited magic.
    BodyNotDelimited,
    /// A block was left with rows still undelimited and its end was asked for
    /// anyway. Walk it before asking for its end.
    BlockNotConsumed {
        trailer: Trailer,
        block: TrailerBlock,
        remaining: usize,
    },
}

// =============================================================================
// Blocks
// =============================================================================

/// A block's end, carrying the ONLY continuation out of it.
///
/// `next` is public because the caller must be able to take it; every other
/// field of every continuation type is private, so this is the whole of the
/// escape surface and it always lands on the next declared block.
#[derive(Debug)]
#[must_use]
pub struct BlockEnd<N> {
    /// The payload offset the block finished at.
    pub at: usize,
    /// The next state of this family's walk.
    pub next: N,
}

/// The pull cursor over one declared block, holding this family's continuation.
///
/// Deliberately neither `Clone` nor `Copy`: a copy would let a caller keep a
/// second route to the continuation and reach the next magic twice.
#[derive(Debug)]
#[must_use]
pub struct BlockCursor<N> {
    rows: RowCursor,
    next: N,
    trailer: Trailer,
    block: TrailerBlock,
}

impl<N> BlockCursor<N> {
    pub(crate) fn new(rows: RowCursor, next: N, trailer: Trailer, block: TrailerBlock) -> Self {
        BlockCursor {
            rows,
            next,
            trailer,
            block,
        }
    }

    /// Which family and which block this is.
    pub const fn trailer(&self) -> Trailer {
        self.trailer
    }

    /// Which block of that family this is.
    pub const fn block(&self) -> TrailerBlock {
        self.block
    }

    /// How many rows this block still has.
    pub const fn remaining(&self) -> usize {
        self.rows.remaining()
    }

    /// The payload offset the block has reached.
    pub const fn offset(&self) -> usize {
        self.rows.offset()
    }

    /// Delimit the next row. The caller reads it with the family's own
    /// `*_row_at`; the OFFSET is never computed at a site.
    pub fn next(&mut self) -> RowStep {
        self.rows.next()
    }

    /// Finish this block and hand back the continuation.
    ///
    /// Refuses when rows are still undelimited. `self` is consumed either way,
    /// so a caller cannot recover the continuation from a refused end and carry
    /// on: the refusal is terminal to this walk, which is the same thing every
    /// structural [`Violation`] already is.
    pub fn into_end(self) -> Result<BlockEnd<N>, Violation> {
        let remaining = self.rows.remaining();
        if remaining != 0 {
            return Err(Violation::caller(
                self.rows.offset(),
                CallerDefect::BlockNotConsumed {
                    trailer: self.trailer,
                    block: self.block,
                    remaining,
                },
            ));
        }
        Ok(BlockEnd {
            at: self.rows.offset(),
            next: self.next,
        })
    }

}

// =============================================================================
// Resuming the parent
// =============================================================================

/// The one route back to the parent cursor.
///
/// Reachable only from a family's FINAL [`BlockEnd`]. Holding one means every
/// declared block of that trailer has been walked or explicitly discarded.
#[derive(Debug)]
#[must_use]
pub struct TrailerResume {
    cursor: crate::TrailerCursor,
    trailer: Trailer,
    end: usize,
}

impl TrailerResume {
    pub(crate) fn new(cursor: crate::TrailerCursor, trailer: Trailer, end: usize) -> Self {
        TrailerResume {
            cursor,
            trailer,
            end,
        }
    }

    /// Where this trailer ended, which is where the next magic begins.
    pub const fn end(&self) -> usize {
        self.end
    }

    /// Which family was just consumed.
    pub const fn trailer(&self) -> Trailer {
        self.trailer
    }

    /// Advance the parent past this trailer and hand it back.
    ///
    /// This is the ONLY operation in the crate that moves the trailer cursor's
    /// offset, clears its pending magic and sets its seen bit. Lane KU's version
    /// did all three inside `read_body`, which is exactly why a forgotten block
    /// was invisible.
    pub fn resume(self) -> crate::TrailerCursor {
        let TrailerResume {
            mut cursor,
            trailer,
            end,
        } = self;
        cursor.advance_past(trailer, end);
        cursor
    }
}

