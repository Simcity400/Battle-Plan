//! The owned walk: a caller cannot advance past a block it did not consume.
//!
//! # What this closes
//!
//! Lane KU shipped a two-step [`TrailerCursor`] whose `read_body` advanced the
//! parent to the trailer's end IMMEDIATELY. A caller could take an `MTRF` body,
//! never call `rows()`, and get the next magic with no refusal. The walk stayed
//! byte-correct — the leaf had computed the extent — but the property the owner
//! ruling asked for ("adding a tail at one site is a compile error at all of
//! them", and its runtime twin, "you cannot forget a block") was not there. It
//! was recorded as that lane's headline residual and made blocking for the first
//! site rewire, which is this one.
//!
//! # The mechanism, and it is ownership
//!
//! [`TrailerCursor`] is neither `Clone` nor `Copy`. There is exactly one of it
//! per walk. [`TrailerCursor::read_body`] takes it **by value**, so the parent
//! stops existing for the duration of the trailer, and the only way to get one
//! back is [`TrailerResume::resume`], which is reachable only through that
//! family's final [`BlockEnd`]. Every declared block of every family is a
//! distinct type transition on the way there:
//!
//! * `MTD1`/`MTRF`/`MTRH`/`MTRB`/`MTLL`: `rows` -> resume.
//! * `MTRR`: `identities` -> `rows` -> resume.
//! * `MTRD`: `witnesses` -> `incomplete_owners` -> `rows` -> resume.
//! * `MTS1`: `countries` -> `items` -> resume.
//! * `MTRA`: header only, so acknowledging the header IS its end.
//!
//! A version that defines no block still passes through the transition with a
//! zero-length cursor (`MTRR` v1/v2 identities, `MTRD` v1/v2 incomplete owners),
//! so the SHAPE of the walk does not change with the version and a site cannot
//! learn a version's absence by skipping a call.
//!
//! `#[must_use]` is on these types as a courtesy. It is not the proof: a warning
//! is not a refusal, and the proof is that the continuation is private and the
//! parent is gone.
//!
//! # Every block is consumed by the shared driver
//!
//! The eager decoder is now the only shipping walk. It visits every row of
//! every declared block, records payload findings without stopping that walk,
//! and reaches the continuation through [`BlockCursor::into_end`]. There is no
//! structural-only bypass: a block left unconsumed is a caller defect.
//!
//! # Why refusal and not a compile error
//!
//! `into_end` returning `Err` is the only shape available. Making an unconsumed
//! block a type error needs the row count in the type, and the row count is on
//! the wire. A `panic!` is not available to a leaf under a recorder that must
//! fail closed, so the misuse is reported as data: a
//! [`ViolationKind::CallerDefect`], which every site's formatter must name
//! separately from a payload defect because it IS a different thing.

